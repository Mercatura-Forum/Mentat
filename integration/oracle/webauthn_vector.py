#!/usr/bin/env python3
"""A real WebAuthn ES256 assertion, generated outside the contract.

The received `signDocument(authToken, requestId)` writes `status = #Signed` and stores nothing a
third party could check. The landed one refuses anything that does not verify against a registered
P-256 key over the digest of the exact content, through the kernel's own verifier.

Proving that requires a REAL signature, and a real signature requires a signer that is not the
thing being tested. This script is that signer. It shares no code with the contract: it recomputes
the challenge from the specification in `Signing.challengeOf` and `Canonical.hashWithDomain` - a
two-byte big-endian length, the domain's UTF-8 bytes, then the payload - and signs the WebAuthn
envelope with `cryptography`'s own P-256 implementation.

Run it with no arguments to print the Motoko literals the evidence battery embeds, or with
`--sign` to print the ones the signing battery embeds: two signers with a key each, signing in the
order the battery's requests name them, with the nonce counter following the battery's own
sequence of `beginSignature` calls.

Attribution: Thebes Core Team. Licence: Apache 2.0.
"""

import base64
import hashlib
import json
import sys

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec

# The contract's signing context, as `EvFold.SIGNING_CTX` declares it.
CONTRACT = "qorza"
ORIGIN = "https://qorza.app"
DOMAIN = "QORZA-SIGN-v1"
RP_ID = "qorza.app"

# A fixed private key, so the vector is reproducible. It signs nothing real and guards nothing.
PRIVATE_SCALAR = 0x0C7A1F3E6D8B2A6084E1C7B35F0D82A472CDABCDF983B077FF50DE6DA42F70710
# The second signer's, for the signing battery; the same caveat.
PRIVATE_SCALAR_2 = 0x5E2D9C0B7A4F318867D0E5C2B19A73F4C6E8D0A2B4C6E8F0A1B3C5D7E9F1A3B5


def hash_with_domain(domain: str, payload: bytes) -> bytes:
    """`Canonical.hashWithDomain`: a 16-bit big-endian length, the domain, then the payload."""
    d = domain.encode("utf-8")
    return hashlib.sha256(len(d).to_bytes(2, "big") + d + payload).digest()


def b64url(b: bytes) -> str:
    """`Signing.b64url`: URL-safe, unpadded."""
    return base64.urlsafe_b64encode(b).decode("ascii").rstrip("=")


def hexs(b: bytes) -> str:
    return b.hex()


def nonce_for(counter: int) -> str:
    """`Signing.begin`: the counter is incremented before the nonce is computed."""
    payload = f"{CONTRACT}|{counter}".encode("utf-8")
    return hexs(hash_with_domain("THEBES-SIGN-NONCE-v1", payload))


def challenge_for(target: str, target_hash: str, nonce: str) -> bytes:
    payload = f"{CONTRACT}|{target}|{target_hash}|{nonce}".encode("utf-8")
    return hash_with_domain(DOMAIN, payload)


def assertion(challenge: bytes, key: ec.EllipticCurvePrivateKey, cross_origin: bool = False):
    client = {
        "type": "webauthn.get",
        "challenge": b64url(challenge),
        "origin": ORIGIN,
    }
    if cross_origin:
        client["crossOrigin"] = True
    client_data = json.dumps(client, separators=(",", ":")).encode("utf-8")
    # authenticatorData: rpIdHash(32) | flags(1) | signCount(4). UP (0x01) and UV (0x04).
    auth_data = hashlib.sha256(RP_ID.encode("utf-8")).digest() + bytes([0x05]) + (1).to_bytes(4, "big")
    signed = auth_data + hashlib.sha256(client_data).digest()
    signature = key.sign(signed, ec.ECDSA(hashes.SHA256()))
    return b64url(client_data), b64url(auth_data), b64url(signature)


def spki_of(key):
    return key.public_key().public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )


def sign_vectors() -> int:
    """The signing battery's scenario (`test/Sign.test.mo`): signer A holds key one, signer B key
    two. Every `beginSignature` the contract accepts advances the nonce counter by one, so the
    counter here follows the battery's accepted begins in order:
      1  A on request 1 (content a)     2  B on request 1
      3  B on request 2 (content b)     4  A on request 4 (content a)
      5  B on request 4 - the signature under it is presented with one byte changed and refused,
         so the challenge stays open and B begins again:
      6  B on request 4, signed properly."""
    a = ec.derive_private_key(PRIVATE_SCALAR, ec.SECP256R1())
    b = ec.derive_private_key(PRIVATE_SCALAR_2, ec.SECP256R1())
    plan = [
        ("1", a, "signature-request:1", "a" * 64, False),
        ("2", b, "signature-request:1", "a" * 64, False),
        ("3", b, "signature-request:2", "b" * 64, False),
        ("4", a, "signature-request:4", "a" * 64, False),
        ("5", b, "signature-request:4", "a" * 64, True),
        ("6", b, "signature-request:4", "a" * 64, False),
    ]
    print("// generated by integration/oracle/webauthn_vector.py --sign - do not edit by hand")
    print(f'let KEY_A : Text = "{b64url(spki_of(a))}";')
    print(f'let KEY_B : Text = "{b64url(spki_of(b))}";')
    for (n, key, target, content, tamper) in plan:
        counter = int(n)
        nonce = nonce_for(counter)
        client, auth, sig = assertion(challenge_for(target, content, nonce), key)
        if tamper:
            raw = base64.urlsafe_b64decode(sig + "=" * (-len(sig) % 4))
            bad = bytearray(raw)
            bad[len(bad) - 1] ^= 0x01
            sig = b64url(bytes(bad))
        print(f'let NONCE_{n} : Text = "{nonce}";')
        print(f'let CLIENT_{n} : Text = "{client}";')
        print(f'let AUTH_{n} : Text = "{auth}";')
        print(f'let SIG_{n}{"_TAMPERED" if tamper else ""} : Text = "{sig}";')
    return 0


def main() -> int:
    if "--sign" in sys.argv:
        return sign_vectors()
    key = ec.derive_private_key(PRIVATE_SCALAR, ec.SECP256R1())
    spki = key.public_key().public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )

    # The battery's own scenario: one document whose plaintext fingerprint is this, one signature
    # request numbered 1, and the first challenge the contract ever opens.
    plain_hash = "a" * 64
    target = "signature-request:1"
    counter = 1
    nonce = nonce_for(counter)
    challenge = challenge_for(target, plain_hash, nonce)
    client_b64, auth_b64, sig_b64 = assertion(challenge, key)

    # and a second one, for the request that is signed after the content has been superseded
    counter2 = 2
    nonce2 = nonce_for(counter2)
    challenge2 = challenge_for("signature-request:2", "b" * 64, nonce2)
    client2, auth2, sig2 = assertion(challenge2, key)

    # and a third: a perfectly formed envelope for the right challenge whose SIGNATURE has one
    # byte changed. Without it the only refusals a battery can reach are "wrong challenge", and
    # "the verifier is actually consulted" would never be tested.
    counter3 = 3
    nonce3 = nonce_for(counter3)
    challenge3 = challenge_for("signature-request:3", "c" * 64, nonce3)
    client3, auth3, sig3 = assertion(challenge3, key)
    raw3 = base64.urlsafe_b64decode(sig3 + "=" * (-len(sig3) % 4))
    tampered = bytearray(raw3)
    tampered[len(tampered) - 1] ^= 0x01
    sig3_bad = b64url(bytes(tampered))

    print("// generated by integration/oracle/webauthn_vector.py - do not edit by hand")
    print(f'let PUBLIC_KEY : Text = "{b64url(spki)}";')
    print(f'let NONCE_1 : Text = "{nonce}";')
    print(f'let CLIENT_1 : Text = "{client_b64}";')
    print(f'let AUTH_1 : Text = "{auth_b64}";')
    print(f'let SIG_1 : Text = "{sig_b64}";')
    print(f'let NONCE_2 : Text = "{nonce2}";')
    print(f'let CLIENT_2 : Text = "{client2}";')
    print(f'let AUTH_2 : Text = "{auth2}";')
    print(f'let SIG_2 : Text = "{sig2}";')
    print(f'let NONCE_3 : Text = "{nonce3}";')
    print(f'let CLIENT_3 : Text = "{client3}";')
    print(f'let AUTH_3 : Text = "{auth3}";')
    print(f'let SIG_3_TAMPERED : Text = "{sig3_bad}";')
    return 0


if __name__ == "__main__":
    sys.exit(main())
